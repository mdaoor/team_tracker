#!/usr/bin/env bash
# One-time (and repeatable) developer/UAT setup on a machine without Docker.
#
#   scripts/setup.sh                 check tools, install Python + Node dependencies, build the deck viewer, write .env
#   scripts/setup.sh --with-db       ...and create the database, run migrations and seed the demo workspace "acme"
#   scripts/setup.sh --no-seed       with --with-db: migrate but do not seed
#   scripts/setup.sh --browsers      ...and download Chromium for PDF/PNG export and Playwright tests
#   scripts/setup.sh --prod          production install: Python deps without dev tools, built web console, no seed
#
# Safe to run again: every step is idempotent.
source "$(dirname "$0")/lib/common.sh"

WITH_DB=0; SEED=1; BROWSERS=0; PROD=0
for a in "$@"; do
  case "$a" in
    --with-db) WITH_DB=1 ;; --no-seed) SEED=0 ;; --browsers) BROWSERS=1 ;; --prod) PROD=1; SEED=0 ;;
    -h|--help) sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) die "unknown option $a (see --help)" ;;
  esac
done
cd "$ROOT" || exit 1

title "1/5 Prerequisites"
run_script doctor.sh --tools-only || die "fix the missing tools above, then run scripts/setup.sh again"

title "2/5 Configuration (.env)"
if [[ -f .env ]]; then
  ok ".env exists (left unchanged)"
else
  cp .env.example .env
  if [[ $PROD -eq 1 ]]; then
    session="$(python3 -c 'import secrets;print(secrets.token_urlsafe(48))')"
    secret="$(python3 -c 'import secrets;print(secrets.token_urlsafe(48))')"
    sed -i.bak -e 's/^TT_ENV=.*/TT_ENV=prod/' -e 's/^TT_DEV_AUTH=.*/TT_DEV_AUTH=0/' \
      -e "s|^TT_SESSION_SECRET=.*|TT_SESSION_SECRET=$session|" .env && rm -f .env.bak
    printf '\n# generated by scripts/setup.sh --prod\nTT_SECRET_KEY=%s\n' "$secret" >> .env
    chmod 600 .env
    ok ".env created for production (TT_ENV=prod, random secrets). Edit TT_DATABASE_URL and the sign-in settings."
  else
    ok ".env created from .env.example (dev defaults: local Postgres tt/tt, Development sign-in on)"
  fi
fi
load_env

title "3/5 Python dependencies (uv)"
if [[ $PROD -eq 1 ]]; then uv sync --all-packages --no-dev; else uv sync --all-packages; fi
ok "Python workspace ready (.venv)"

title "4/5 Node dependencies (pnpm) and builds"
pnpm install --frozen-lockfile
pnpm --filter @tt/presentation build
ok "deck viewer built (apps/presentation/dist/presentation.html)"
if [[ $PROD -eq 1 ]]; then
  pnpm --filter @tt/web build
  ok "web console built (apps/web/dist) - serve it with your web server, see docs/guide/04-production.md"
fi
if [[ $BROWSERS -eq 1 ]]; then
  pnpm --filter @tt/web exec playwright install chromium
  ok "Chromium installed for PDF/PNG export and Playwright"
fi

title "5/5 Database"
if [[ $WITH_DB -eq 1 ]]; then
  run_script db.sh start
  run_script db.sh create
  run_script db.sh migrate
  if [[ $SEED -eq 1 ]]; then run_script db.sh seed; fi
else
  echo "skipped (run: scripts/ttctl db setup   - or re-run with --with-db)"
fi

title "Done"
cat <<EOF
Next:
  scripts/ttctl start          start API, worker and web console in the background
  scripts/ttctl status         see what is running
  open http://localhost:$TT_WEB_PORT/login   (Development sign-in: workspace acme, handle @mahmoud)
EOF
