"""StorageAdapter: put / get / delete bytes by an opaque key. `LocalDiskStorage` is the v1 implementation.

Keys are generated by the server from ids (never from filenames), so a hostile filename cannot reach the filesystem; the adapter
still refuses anything that resolves outside its root."""

from __future__ import annotations

import hashlib
import hmac
import os
from datetime import UTC, datetime
from pathlib import Path
from typing import Protocol
from urllib.parse import quote

import httpx


class StorageError(Exception):
    pass


class StorageAdapter(Protocol):
    scheme: str

    async def put(self, key: str, data: bytes) -> str: ...
    async def get(self, url: str) -> bytes: ...
    async def delete(self, url: str) -> None: ...


class LocalDiskStorage:
    scheme = "local"

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()

    def _path(self, key: str) -> Path:
        p = (self.root / key).resolve()
        if self.root != p and self.root not in p.parents:
            raise StorageError("key escapes the storage root")
        return p

    async def put(self, key: str, data: bytes) -> str:
        p = self._path(key)
        p.parent.mkdir(parents=True, exist_ok=True)
        tmp = p.with_name(p.name + ".part")
        tmp.write_bytes(data)
        os.replace(tmp, p)  # atomic: a reader never sees half a file
        return f"{self.scheme}://{key}"

    def _key(self, url: str) -> str:
        if not url.startswith(f"{self.scheme}://"):
            raise StorageError(f"not a {self.scheme} url")
        return url.split("://", 1)[1]

    async def get(self, url: str) -> bytes:
        p = self._path(self._key(url))
        if not p.is_file():
            raise StorageError("blob missing")
        return p.read_bytes()

    async def delete(self, url: str) -> None:
        self._path(self._key(url)).unlink(missing_ok=True)


def checksum(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


# ---------------------------------------------------------------------------------------------------- S3 (SigV4 pre-signed URLs)
def presign(
    method: str,
    *,
    host: str,
    path: str,
    region: str,
    access_key: str,
    secret_key: str,
    expires: int = 900,
    now: datetime | None = None,
    service: str = "s3",
    extra: dict[str, str] | None = None,
) -> str:
    """AWS Signature V4 query-string pre-signing (path-style or virtual-hosted: the caller decides `host` and `path`)."""
    t = (now or datetime.now(UTC)).astimezone(UTC)
    amz_date, day = t.strftime("%Y%m%dT%H%M%SZ"), t.strftime("%Y%m%d")
    scope = f"{day}/{region}/{service}/aws4_request"
    params = {
        "X-Amz-Algorithm": "AWS4-HMAC-SHA256",
        "X-Amz-Credential": f"{access_key}/{scope}",
        "X-Amz-Date": amz_date,
        "X-Amz-Expires": str(expires),
        "X-Amz-SignedHeaders": "host",
        **(extra or {}),
    }
    query = "&".join(f"{quote(k, safe='')}={quote(v, safe='')}" for k, v in sorted(params.items()))
    canonical_path = quote(path, safe="/~")
    canonical = "\n".join([method, canonical_path, query, f"host:{host}\n", "host", "UNSIGNED-PAYLOAD"])
    to_sign = "\n".join(["AWS4-HMAC-SHA256", amz_date, scope, hashlib.sha256(canonical.encode()).hexdigest()])

    def h(key: bytes, msg: str) -> bytes:
        return hmac.new(key, msg.encode(), hashlib.sha256).digest()

    k = h(h(h(h(f"AWS4{secret_key}".encode(), day), region), service), "aws4_request")
    sig = hmac.new(k, to_sign.encode(), hashlib.sha256).hexdigest()
    return f"https://{host}{canonical_path}?{query}&X-Amz-Signature={sig}"


class S3Storage:
    """S3-compatible object storage (AWS, MinIO, Ceph). Bytes go through short-lived pre-signed URLs; downloads can be redirected to one."""

    scheme = "s3"

    def __init__(
        self,
        bucket: str,
        *,
        region: str,
        access_key: str,
        secret_key: str,
        endpoint: str | None = None,
        client: httpx.AsyncClient | None = None,
        prefix: str = "",
    ) -> None:
        self.bucket, self.region, self.ak, self.sk, self.prefix = (
            bucket,
            region,
            access_key,
            secret_key,
            prefix.strip("/"),
        )
        self.endpoint = (endpoint or "").rstrip("/")
        self.http = client or httpx.AsyncClient(timeout=30)
        self.path_style = bool(endpoint)

    def _where(self, key: str) -> tuple[str, str]:
        k = "/".join(p for p in (self.prefix, key.lstrip("/")) if p)
        if ".." in k.split("/"):
            raise StorageError("key escapes the prefix")
        if self.path_style:
            host = self.endpoint.split("://", 1)[1]
            return host, f"/{self.bucket}/{k}"
        return f"{self.bucket}.s3.{self.region}.amazonaws.com", f"/{k}"

    def url_for(
        self,
        method: str,
        key: str,
        *,
        expires: int = 900,
        now: datetime | None = None,
        extra: dict[str, str] | None = None,
    ) -> str:
        host, path = self._where(key)
        url = presign(
            method,
            host=host,
            path=path,
            region=self.region,
            access_key=self.ak,
            secret_key=self.sk,
            expires=expires,
            now=now,
            extra=extra,
        )
        if self.path_style and self.endpoint.startswith("http://"):
            url = "http://" + url.split("://", 1)[1]
        return url

    def _key(self, url: str) -> str:
        if not url.startswith("s3://"):
            raise StorageError("not an s3 url")
        return url.split("://", 1)[1]

    async def put(self, key: str, data: bytes) -> str:
        r = await self.http.put(self.url_for("PUT", key), content=data)
        if r.status_code >= 300:
            raise StorageError(f"s3 put failed: {r.status_code}")
        return f"s3://{key}"

    async def get(self, url: str) -> bytes:
        r = await self.http.get(self.url_for("GET", self._key(url)))
        if r.status_code == 404:
            raise StorageError("blob missing")
        if r.status_code >= 300:
            raise StorageError(f"s3 get failed: {r.status_code}")
        return r.content

    async def delete(self, url: str) -> None:
        r = await self.http.delete(self.url_for("DELETE", self._key(url)))
        if r.status_code >= 300 and r.status_code != 404:
            raise StorageError(f"s3 delete failed: {r.status_code}")

    def signed_download_url(
        self, url: str, *, expires: int = 120, disposition: str | None = None, content_type: str | None = None
    ) -> str:
        """The object store applies `response-content-*` overrides, so a forced download stays forced."""
        extra = {}
        if disposition:
            extra["response-content-disposition"] = disposition
        if content_type:
            extra["response-content-type"] = content_type
        return self.url_for("GET", self._key(url), expires=expires, extra=extra or None)


def adapter_from_settings(settings: object) -> StorageAdapter:
    if getattr(settings, "attachment_backend", "local") == "s3":
        return S3Storage(
            settings.s3_bucket,  # type: ignore[attr-defined]
            region=settings.s3_region,  # type: ignore[attr-defined]
            access_key=settings.s3_access_key,  # type: ignore[attr-defined]
            secret_key=settings.s3_secret_key,  # type: ignore[attr-defined]
            endpoint=getattr(settings, "s3_endpoint", None),
            prefix=getattr(settings, "s3_prefix", ""),
        )
    return LocalDiskStorage(getattr(settings, "attachment_dir", "./var/attachments"))
